#!/usr/bin/env python3
"""Build a link-preview page for each keyboard.

Link-preview bots don't run JavaScript or see URL fragments, so every
#kb-<id> link shares the site-wide preview. This writes k/<id>/index.html
with that keyboard's Open Graph tags, which then redirects people to
/#kb-<id>. Keyboards with a photo get a 1200x630 image in images/og/;
the rest use images/og-preview.jpg.

Requires Pillow. Run from anywhere: python3 tools/build_previews.py
Pass --force to rebuild preview images that already exist.
"""

import html
import json
import shutil
import sys
from pathlib import Path

from PIL import Image, ImageEnhance, ImageFilter, ImageOps

SITE = "https://melsumner.github.io/keebs/"
SITE_NAME = "Mel’s Keebs"
ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "keyboard_collection.json"
PAGES = ROOT / "k"
OG_DIR = ROOT / "images" / "og"
DEFAULT_IMAGE = "images/og-preview.jpg"
DEFAULT_ALT = "“Mel’s Keebs” over a photo of a dark navy tenkeyless keyboard with matching navy keycaps."
W, H = 1200, 630


def text(value):
    return value.strip() if isinstance(value, str) and value.strip() else None


def join(*parts, sep=" "):
    return sep.join(p for p in map(text, parts) if p)


def og_image(photo, force):
    """Fit the whole card photo in 1200x630 over a blurred, darkened copy of itself (like the cards do).
    Named after the source photo, so a new photo gets a new file."""
    src = ROOT / photo
    out = OG_DIR / src.name
    if force or not out.exists():
        with Image.open(src) as im:
            im = ImageOps.exif_transpose(im).convert("RGB")
            bg = ImageOps.fit(im, (W // 8, H // 8)).filter(ImageFilter.GaussianBlur(3)).resize((W, H), Image.LANCZOS)
            bg = ImageEnhance.Brightness(bg).enhance(0.6)
            fg = ImageOps.contain(im, (W, H), Image.LANCZOS)
            bg.paste(fg, ((W - fg.width) // 2, (H - fg.height) // 2))
            bg.save(out, "JPEG", quality=80, optimize=True, progressive=True)
    return out


def description(b):
    sw = b.get("switches") or {}
    kc = b.get("keycaps") or {}
    case = b.get("case") or {}
    switch = text(sw.get("model")) or text(sw.get("description"))
    if switch and text(sw.get("type")):
        switch = f"{switch} ({sw['type'].strip()})"
    keycaps = text(kc.get("set"))
    if keycaps and text(kc.get("profile")):
        keycaps = f"{keycaps} ({kc['profile'].strip()} profile)"
    parts = [
        f"Switches: {switch}." if switch else None,
        f"Keycaps: {keycaps}." if keycaps else None,
        f"Case: {join(case.get('color_or_finish'), case.get('material'), sep=', ')}." if join(case.get("color_or_finish"), case.get("material")) else None,
    ]
    return join(*parts) or "A build from my mechanical keyboard collection."


def page(b, image, alt):
    name = join(b.get("brand"), b.get("model")) or f"Keyboard #{b['id']}"
    title = f"{name} · {SITE_NAME}"
    url = f"{SITE}k/{b['id']}/"
    target = f"../../#kb-{b['id']}"
    e = lambda s: html.escape(s, quote=True)
    return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <!-- Generated by tools/build_previews.py. Don't edit by hand. -->
  <title>{e(title)}</title>
  <meta name="description" content="{e(description(b))}">
  <meta name="color-scheme" content="dark">
  <link rel="canonical" href="{e(url)}">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="{e(SITE_NAME)}">
  <meta property="og:title" content="{e(name)}">
  <meta property="og:description" content="{e(description(b))}">
  <meta property="og:url" content="{e(url)}">
  <meta property="og:locale" content="en_US">
  <meta property="og:image" content="{e(SITE + image)}">
  <meta property="og:image:type" content="image/jpeg">
  <meta property="og:image:width" content="{W}">
  <meta property="og:image:height" content="{H}">
  <meta property="og:image:alt" content="{e(alt)}">
  <meta name="twitter:card" content="summary_large_image">
  <script>location.replace({json.dumps(target)});</script>
  <style>body{{background:#0d1330;color:#e8ebf7;font:1.125rem/1.5 system-ui,sans-serif;padding:2rem}}a{{color:#c4b5fd}}</style>
</head>
<body>
  <main>
    <h1>{e(name)}</h1>
    <p><a href="{e(target)}">View the {e(name)} on {e(SITE_NAME)}</a></p>
  </main>
</body>
</html>
"""


def main():
    force = "--force" in sys.argv[1:]
    builds = json.loads(DATA.read_text(encoding="utf-8"))["builds"]
    OG_DIR.mkdir(parents=True, exist_ok=True)

    keep_images, keep_pages = set(), set()
    for b in builds:
        name = join(b.get("brand"), b.get("model")) or f"keyboard #{b['id']}"
        if text(b.get("photo")) and (ROOT / b["photo"]).exists():
            out = og_image(b["photo"], force)
            keep_images.add(out.name)
            image, alt = out.relative_to(ROOT).as_posix(), f"Photo of the {name} keyboard."
        else:
            image, alt = DEFAULT_IMAGE, DEFAULT_ALT
        folder = PAGES / str(b["id"])
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "index.html").write_text(page(b, image, alt), encoding="utf-8")
        keep_pages.add(folder.name)

    # Clean up after removed photos and keyboards.
    for f in OG_DIR.iterdir():
        if f.name not in keep_images:
            f.unlink()
    for d in PAGES.iterdir():
        if d.name not in keep_pages:
            shutil.rmtree(d) if d.is_dir() else d.unlink()

    print(f"{len(keep_pages)} pages, {len(keep_images)} preview images")


if __name__ == "__main__":
    main()
